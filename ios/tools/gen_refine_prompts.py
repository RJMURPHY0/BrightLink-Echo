"""Regenerate ios/App/Cloud/RefinePrompts.swift from ai_refiner.py.

Run from the repo root:  python3 -I ios/tools/gen_refine_prompts.py
The phone and the PC must send the relay identical prompts, so the Swift file
is generated, never hand-edited. CI (ios.yml) fails if it is out of date.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT)
import ai_refiner as a  # noqa: E402

OUT = os.path.join(ROOT, "ios", "App", "Cloud", "RefinePrompts.swift")
MODES = ["punctuation", "email", "formal", "casual", "concise"]
CUSTOM_SUFFIX = (
    " Do exactly what the instruction above asks and nothing more. "
    "Keep the speaker's meaning and every point they made unless "
    "the instruction explicitly asks you to change them."
)


def lit(s: str) -> str:
    """A Swift string literal. JSON escapes are Swift escapes, except \\uXXXX."""
    return re.sub(r"\\u([0-9a-fA-F]{4})", r"\\u{\1}", json.dumps(s, ensure_ascii=True))


def render() -> str:
    r = a.AIRefiner
    lines = [
        "// GENERATED by ios/tools/gen_refine_prompts.py from ai_refiner.py.",
        "// Do not hand-edit: regenerate so the phone and the PC refine identically.",
        "import Foundation",
        "",
        "enum RefinePrompts {",
        "    static let modes: [String: String] = [",
    ]
    lines += [f'        "{m}": {lit(a.REFINE_PROMPTS[m])},' for m in MODES]
    lines += [
        "    ]",
        f"    static let styleSystem = {lit(r._STYLE_SYSTEM_PROMPT)}",
        f"    static let editorSystem = {lit(r._EDITOR_SYSTEM_PROMPT)}",
        f"    static let dataNote = {lit(a._DATA_NOTE)}",
        f"    static let dataOpen = {lit(a._DATA_OPEN)}",
        f"    static let dataClose = {lit(a._DATA_CLOSE)}",
        f"    static let keepEmoji = {lit(a._KEEP_EMOJI)}",
        f"    static let customAskSuffix = {lit(CUSTOM_SUFFIX)}",
        "}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("RefinePrompts.swift is out of date: run python3 -I ios/tools/gen_refine_prompts.py")
        print("RefinePrompts.swift is up to date")
    else:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", OUT)
